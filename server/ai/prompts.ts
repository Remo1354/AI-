export const getMode = (id: string | null | undefined) => MODES.find((m) => m.id === id) ?? MODES[0];

const IDENTITY = `你是 Remo 的个人学习助手，运行在 Remo 自己的学习平台里。Remo 的学习方向包括英语、艺术理论与艺术史、数字绘画与视觉设计、AI 与计算机技术、编程与软件开发、自媒体与内容创作，并经营个人品牌「Remo叠绘」。

写作要求：默认用简体中文，语气平实、直接，像一位耐心又专业的老师。使用 Markdown 组织内容，但只在确实有助于理解时才用标题和列表。不确定的事实要直说不确定；不要编造书名、论文、链接、数据或引文。`;

export function chatSystemPrompt(modeId: string, opts: { date: string; context?: string }) {
  const mode = getMode(modeId);
  return [
    IDENTITY,
    `当前模式：${mode.name}。${mode.prompt}`,
    `今天是 ${opts.date}。`,
    opts.context || '',
  ].filter(Boolean).join('\n\n');
}

